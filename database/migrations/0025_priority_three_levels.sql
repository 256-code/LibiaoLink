-- LibiaoLink · 0025 紧急重要度收敛三档（M3-07 · Push 163：口径以前端页面为准「高 / 中 / 低」）
-- 口径来源：字段对照清单.md「紧急重要度」一列（页面三档）、前端功能需求.md §二.4 / §三（任务表 / 抽屉 / 行内编辑同一套值）、
--   契约 shared/src/common/dicts.ts 的 PRIORITY_VALUES（Push 163 同步收敛）。
--   1. 背景：契约原为四象限（重要且紧急 / 紧急但不重要 / 重要不紧急 / 不紧急不重要），与页面口径不一致 ——
--      Push 163 定案「页面口径为准」：契约与库值改成三档，前端不做任何折算（Push 162 的「页面跟契约走」已撤回）。
--   2. 存量折算（一次性、幂等）：重要且紧急 → 高；重要不紧急 / 紧急但不重要 → 中；不紧急不重要 → 低。
--      折算有损（三档回不到四象限），不提供自动回滚；如需回退请从备份恢复。
--   3. tasks.priority 是 text（无 CHECK、无枚举类型），本次**无 DDL**、只改存量值；应用角色权限不变。
update tasks
   set priority = case priority
     when '重要且紧急' then '高'
     when '重要不紧急' then '中'
     when '紧急但不重要' then '中'
     when '不紧急不重要' then '低'
   end
 where priority in ('重要且紧急', '重要不紧急', '紧急但不重要', '不紧急不重要');
